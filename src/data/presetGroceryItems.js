// A catalog of what actually shows up on a market/grocery run, so picking
// "Egg" from a list — instead of free-typing "egg" one week and "Eggs" the
// next — is the easy path. Reports/frequency tracking matches by exact
// name, so consistent picks here are what makes that tracking useful.
// Skews toward common West African market staples (given the ₦ pricing
// throughout the app) alongside the usual supermarket basics. Anything
// missing is one "+ Add as new item" away — see useCustomGroceryItems.

